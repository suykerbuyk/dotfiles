#!/usr/bin/env bash
set -euo pipefail

# podman installer — static, ROOTLESS podman from mgoltzsche/podman-static.
#
# Peculiarity (why this is not a single-binary install_bin fetcher): the release
# tarball is a whole userland tree (podman + crun/runc/pasta/fuse-overlayfs plus
# helper binaries conmon/netavark/aardvark-dns/rootlessport/quadlet), and podman
# resolves those helpers via *config files that embed absolute paths* into the
# extracted version dir — NOT via PATH. So this mirrors the go/ninja whole-tree
# pattern: extract into ~/.local/apps/podman-<ver>/, symlink ONLY podman onto
# PATH, and (re)generate host-local config every run so the embedded paths always
# point at the live version dir. See home/doc/fetch-bins.md.
#
# It also emits two host-local artifacts the committed tree does NOT carry:
#   - ~/.config/containers/{containers,storage}.conf (+ copied policy/registries/
#     seccomp) — regenerated every run because they embed the version path.
#   - ~/.local/bin/podman-rootless-setup — a distro-aware, root-run helper that
#     provisions the subuid/subgid ranges, uidmap, and userns sysctl that full
#     multi-UID rootless podman needs. Generated here via a quoted heredoc so it
#     resolves $USER/$SUDO_USER at *its* run time, not at generation time.
#
# The fetcher never runs `podman info`/`podman run` (those need XDG_RUNTIME_DIR
# and a userns and would break a headless install) — only `podman --version`.
# After install it prints a STATE-AWARE rootless-readiness message but always
# exits 0: rootless prereqs are advisory, not a failure of the install.

. "$(dirname "$(realpath "${BASH_SOURCE[0]}")")/_lib.sh"

BIN_NAME="podman"
fb_init

ARCH="$(fb_arch amd64)"   # amd64 | arm64

TAG="$(gh_latest_tag mgoltzsche/podman-static)"
ver="${TAG#v}"

# Asset carries no version token in its name: podman-linux-<arch>.tar.gz
ASSET="podman-linux-${ARCH}.tar.gz"
ASSET_URL="$(gh_asset_url mgoltzsche/podman-static '. == $arch' "$ASSET")"

VERSION_DIR="${APP_DIR}/podman-${ver}"
# <app> prefix used by every embedded config path below. The tarball's top dir
# (podman-linux-<arch>/) is stripped, so usr/local lands directly under it.
APP="${VERSION_DIR}/usr/local"

CONF_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/containers"
DATA="${XDG_DATA_HOME:-$HOME/.local/share}"

link_podman() {
    # Only podman goes on PATH; helpers resolve via config, not PATH.
    ln -sfn "$APP/bin/podman" "${BIN_DIR}/podman"
}

# --- config + setup generation -------------------------------------------------
# Regenerated EVERY run (fast path and fresh install alike) because the paths
# embed $APP / $VERSION_DIR, which change with the version.
gen_configs() {
    mkdir -p "$CONF_DIR"

    # containers.conf — conmon needs its OWN conmon_path; helper_binaries_dir
    # does NOT cover conmon (without conmon_path podman dies "could not find a
    # working conmon binary").
    cat > "${CONF_DIR}/containers.conf" <<EOF
[engine]
cgroup_manager = "cgroupfs"
events_logger = "file"
conmon_path = ["${APP}/lib/podman/conmon"]
helper_binaries_dir = ["${APP}/lib/podman", "${APP}/libexec/podman", "${APP}/bin"]
runtime = "crun"

[engine.runtimes]
crun = ["${APP}/bin/crun"]
runc = ["${APP}/bin/runc"]
EOF

    # storage.conf — OMIT runroot (podman derives \$XDG_RUNTIME_DIR/containers; a
    # fixed on-disk runroot would be wrong). graphroot under XDG_DATA_HOME.
    cat > "${CONF_DIR}/storage.conf" <<EOF
[storage]
driver = "overlay"
graphroot = "${DATA}/containers/storage"

[storage.options.overlay]
mount_program = "${APP}/bin/fuse-overlayfs"
ignore_chown_errors = "true"
mountopt = "nodev,fsync=0"
EOF

    # policy.json is mandatory (podman refuses pulls without it); registries.conf
    # and seccomp.json are copied verbatim — no path substitution needed. Copy
    # each only if the shipped source exists.
    local f
    for f in policy.json registries.conf seccomp.json; do
        if [[ -f "${VERSION_DIR}/etc/containers/${f}" ]]; then
            cp -f "${VERSION_DIR}/etc/containers/${f}" "${CONF_DIR}/${f}"
        fi
    done
}

# Emit ~/.local/bin/podman-rootless-setup. QUOTED heredoc delimiter so $USER,
# $SUDO_USER, etc. are resolved when the generated script runs (as root), not
# now. The generated script is idempotent and distro-aware.
gen_setup_script() {
    cat > "${BIN_DIR}/podman-rootless-setup" <<'SETUP_EOF'
#!/usr/bin/env bash
set -euo pipefail

# podman-rootless-setup — provision the host-level prerequisites for full
# multi-UID rootless podman. Run as root: `sudo podman-rootless-setup`.
# Idempotent and distro-aware. Generated by fetch.bins/12_fetch.podman.sh.

# Target the invoking unprivileged user, not root.
user="${SUDO_USER:-$USER}"
if [[ "$user" == "root" || -z "$user" ]]; then
    echo "Refusing to configure rootless podman for 'root'." >&2
    echo "Run as: sudo podman-rootless-setup   (from your normal user account)." >&2
    exit 1
fi

echo "Configuring rootless podman prerequisites for user: $user"

# --- subuid / subgid ----------------------------------------------------------
# Add '$user:100000:65536' only if the user is ABSENT (any existing range means
# done — never append a second line for the same user).
for f in /etc/subuid /etc/subgid; do
    [[ -f "$f" ]] || touch "$f"
    if grep -q "^${user}:" "$f"; then
        echo "  $f: '$user' already has a range — leaving as-is."
    else
        echo "${user}:100000:65536" >> "$f"
        echo "  $f: added '${user}:100000:65536'."
    fi
done

# --- uidmap (newuidmap/newgidmap) --------------------------------------------
if command -v newuidmap >/dev/null 2>&1; then
    echo "  newuidmap: present."
else
    echo "  newuidmap: missing — installing the uidmap package."
    if command -v apt-get >/dev/null 2>&1; then
        apt-get install -y uidmap
    elif command -v apt >/dev/null 2>&1; then
        apt install -y uidmap
    elif command -v dnf >/dev/null 2>&1; then
        dnf install -y shadow-utils
    elif command -v pacman >/dev/null 2>&1; then
        pacman -S --noconfirm shadow
    elif command -v zypper >/dev/null 2>&1; then
        zypper install -y shadow
    else
        echo "  WARNING: no known package manager found; install newuidmap/newgidmap" >&2
        echo "           (the 'uidmap' or 'shadow-utils' package) manually." >&2
    fi
fi

# --- unprivileged user namespaces --------------------------------------------
# Only act if the knob EXISTS and is disabled. Modern kernels (e.g. Debian 13)
# dropped kernel.unprivileged_userns_clone and default-enable userns — in that
# case there is nothing to do, and probing a nonexistent knob must not error.
knob="kernel.unprivileged_userns_clone"
if sysctl -n "$knob" >/dev/null 2>&1; then
    cur="$(sysctl -n "$knob" 2>/dev/null || echo 1)"
    if [[ "$cur" == "0" ]]; then
        echo "  $knob is 0 — enabling and persisting."
        sysctl -w "${knob}=1"
        mkdir -p /etc/sysctl.d
        echo "${knob} = 1" > /etc/sysctl.d/99-podman-rootless.conf
    else
        echo "  $knob already enabled ($cur)."
    fi
else
    echo "  $knob not present — modern kernel default-enables userns; nothing to do."
fi

echo
echo "Done. If you just switched podman between root and rootless modes, run:"
echo "    podman system migrate"
SETUP_EOF
    chmod +x "${BIN_DIR}/podman-rootless-setup"
}

# --- rootless readiness message (advisory, never fatal) -----------------------
print_rootless_state() {
    local userns_ok=1 have_range=1 have_newuidmap=1
    local me="${USER:-$(id -un)}"
    unshare --user true 2>/dev/null || userns_ok=0
    grep -q "^${me}:" /etc/subuid 2>/dev/null || have_range=0
    command -v newuidmap >/dev/null 2>&1 || have_newuidmap=0

    if [[ "$userns_ok" == 0 ]]; then
        echo "podman installed, but unprivileged user namespaces are disabled — run: sudo podman-rootless-setup"
    elif [[ "$have_range" == 0 ]]; then
        echo "podman works now in single-UID mode. For full multi-UID rootless: sudo podman-rootless-setup"
    elif [[ "$have_newuidmap" == 0 ]]; then
        echo "podman installed, but a subuid range exists without newuidmap — podman will fail until you run: sudo podman-rootless-setup (installs uidmap)"
    else
        echo "podman ready (full rootless: subuid range + newuidmap present)"
    fi
}

# --- prune older version dirs (pure cache, ~85MB each) ------------------------
prune_old_versions() {
    local d
    for d in "${APP_DIR}"/podman-*; do
        [[ -d "$d" ]] || continue
        [[ "$d" == "$VERSION_DIR" ]] && continue
        echo "  pruning old podman version dir: $d"
        rm -rf "$d"
    done
}

# ------------------------------------------------------------------------------
# Fast path: this exact version is already extracted and runnable. Re-assert the
# symlink and regenerate the configs + setup script (they embed the version
# path, so they are self-healed every run), then exit.
if [[ -x "$APP/bin/podman" ]] && "$APP/bin/podman" --version >/dev/null 2>&1; then
    echo "podman $ver already installed; symlink + config ensured -> $APP/bin/podman"
    link_podman
    gen_configs
    gen_setup_script
    print_rootless_state
    exit 0
fi

# Fresh install: remove any partial/old extraction of THIS version dir first.
rm -rf "$VERSION_DIR"

TARBALL="${FB_TMP}/podman.tar.gz"
gh_download "$ASSET_URL" "$TARBALL"

mkdir -p "$VERSION_DIR"
# Top dir podman-linux-<arch>/ wraps usr/ + etc/ + README.md; strip it.
tar -C "$VERSION_DIR" -xzf "$TARBALL" --strip-components=1

# Verify in place — version check only (no info/run; see header).
if ! "$APP/bin/podman" --version >/dev/null 2>&1; then
    echo "Error: extracted podman is not runnable at $APP/bin/podman" >&2
    exit 1
fi

link_podman
gen_configs
gen_setup_script

# Only after a successful NEW install: drop other podman-* version dirs.
prune_old_versions

echo "Installed podman $ver (mgoltzsche/podman-static) to $VERSION_DIR"
echo "  version: $("$APP/bin/podman" --version)"
echo "  config:  $CONF_DIR"
echo "  setup:   ${BIN_DIR}/podman-rootless-setup"
print_rootless_state
